TABLES = {"zh": ZH, "en": EN}


def set_lang(lang: str) -> None:
    global _LANG
    _LANG = lang if lang in TABLES else "zh"


def get_lang() -> str:
    return _LANG


def tr(key: str, **kw) -> str:
    s = TABLES.get(_LANG, {}).get(key) or EN.get(key) or key
    return s.format(**kw) if kw else s


def role_label(role: str) -> str:
    key = "role_" + role
    return TABLES.get(_LANG, {}).get(key) or EN.get(key) or role
